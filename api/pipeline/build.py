"""Rebuild everything: simulate, load the warehouse, train, score, document.

    python -m pipeline.build                  # uses DATABASE_URL
    python -m pipeline.build --no-db          # simulate and train only, print the report

The model card and simulation notes in docs/ are written from the run's own numbers.
"""

from __future__ import annotations

import argparse
import json
import os
import time
from datetime import date, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import bcrypt
import psycopg

from pipeline import model as mdl
from pipeline.simulate import EFFECTS, add_months, simulate
from pipeline.warehouse import build as build_warehouse

DOCS = Path(__file__).resolve().parents[2] / "docs"
SEED = 20261106
PLANTED = {
    "pay_ratio",
    "months_since_promotion",
    "manager_changed_6m",
    "overtime_3m",
    "rating",
    "tenure_months",
}


def last_full_month() -> date:
    today = datetime.now(ZoneInfo("Asia/Jakarta")).date()
    return add_months(today.replace(day=1), -1)


def write_docs(trained: mdl.TrainedModel, end: date, counts: dict | None) -> None:
    DOCS.mkdir(exist_ok=True)
    m = trained.metrics
    pit = m["point_in_time"]
    top = [r["feature"] for r in trained.importance[:6]]
    recovered = sorted(PLANTED & set(top))
    lines = [
        "# Model card: voluntary attrition risk",
        "",
        f"Generated by `python -m pipeline.build` for data ending {end:%B %Y}. Model `{trained.version}`.",
        "",
        "## What it is for",
        "",
        "A ranked list of employees who are more likely than their colleagues to resign in the next",
        "six months, with the factors behind each score, so an HR business partner can start a",
        "conversation about pay, workload or career early. It is **not** for decisions about",
        "individuals: not for performance ratings, promotion, discipline or termination.",
        "",
        "## Data",
        "",
        "Synthetic. A month-by-month simulation of a fictional insurer (see `simulation.md`), so",
        "the true causes of attrition are known and the model can be checked against them.",
        f"Rows are employee-months; the label is a voluntary exit in the following {mdl.HORIZON} months.",
        "",
        "| Split | Months | Employee-months |",
        "|---|---|---|",
    ]
    for k in ("train", "valid", "test", "score"):
        a, b = trained.splits[k]
        lines.append(f"| {k} | {a} to {b} | {m['rows'][k]:,} |")
    lines += [
        "",
        "Features: " + ", ".join(f"`{f}`" for f in mdl.FEATURES) + ".",
        "Gender and age are deliberately **not** features; they are used only in the audit below.",
        "",
        "## Results on the test months",
        "",
        f"- Base rate: {m['base_rate'] * 100:.1f}% of employee-months are followed by a voluntary exit within six months.",
        f"- ROC-AUC {m['roc_auc']}, PR-AUC {m['pr_auc']} (a random ranking would score PR-AUC ≈ {m['base_rate']:.3f}).",
        f"- Brier score {m['brier_raw']} before calibration, {m['brier_calibrated']} after.",
        f"- **Ceiling:** ranking the same rows by the true planted formula (which no real dataset would"
        f" have, and without the unobserved personal factor) scores ROC-AUC {m['ceiling']['roc_auc']} and"
        f" PR-AUC {m['ceiling']['pr_auc']}. Most of the distance to a perfect score is noise in who decides"
        f" to leave, not something better modelling could recover.",
        f"- Scoring a single month ({pit['month']}, {pit['employees']} employees, {pit['leavers_next_6m']} of whom resigned"
        f" within six months): the top 10% ({pit['top_10pct']['flagged']} people) contained"
        f" {pit['top_10pct']['recall'] * 100:.0f}% of those leavers, a lift of {pit['top_10pct']['lift']}× over picking at random.",
        "",
        "### Calibration (test months, deciles of predicted probability)",
        "",
        "| Decile | Predicted | Observed | n |",
        "|---|---|---|---|",
        *[
            f"| {c['bucket'] + 1} | {c['predicted']:.3f} | {c['observed']:.3f} | {c['n']} |"
            for c in trained.calibration
        ],
        "",
        "## What drives the scores",
        "",
        "Mean absolute TreeSHAP contribution on the test months:",
        "",
        "| Feature | Mean abs. SHAP | Gain share |",
        "|---|---|---|",
        *[
            f"| `{r['feature']}` | {r['mean_abs_shap']} | {r['gain_share']:.1%} |"
            for r in trained.importance
        ],
        "",
        f"Of the six planted drivers that are observable as features, {len(recovered)} appear in the top six:"
        f" {', '.join(f'`{x}`' for x in recovered) or 'none'}. Recovering planted effects shows the pipeline",
        "works; it says nothing about which drivers matter in a real workforce.",
        "",
        "## Fairness audit",
        "",
        f"Flags are the top 10% of scores on the test months (threshold {trained.fairness['threshold_top_10pct']}).",
        "",
    ]
    for attr, title in (("gender", "Gender"), ("age_band", "Age band")):
        a = trained.fairness[attr]
        lines += [
            f"**{title}** (flag-rate ratio, smallest over largest group with n ≥ 100: {a['flag_rate_ratio_min_max']})",
            "",
            "| Group | n | Observed rate | Mean predicted | Flag rate | Recall |",
            "|---|---|---|---|---|---|",
            *[
                f"| {g['group']} | {g['n']:,} | {g['observed_rate']:.3f} | {g['mean_predicted']:.3f} | {g['flag_rate']:.3f} | "
                f"{'—' if g['recall'] is None else g['recall']} |"
                for g in a["groups"]
            ],
            "",
        ]
    lines += [
        "Equal flag rates are not the goal when underlying rates differ; the table shows whether flags",
        "track observed outcomes in each group. Large gaps between *observed rate* and *mean predicted*",
        "for a group would mean the model is miscalibrated for that group, which is what to watch.",
        "",
        "## Limitations",
        "",
        "- Trained on simulated data with a known, simple structure. Real attrition has causes no HRIS records.",
        "- Six months of horizon and monthly snapshots; a resignation decided in the last week of a month",
        "  is invisible until the next snapshot.",
        "- Scores are relative within the scored month (top 10% = high, next 20% = elevated).",
        "- Access: individual scores only for HR admins and HRBPs in scope; leaders see aggregates.",
    ]
    (DOCS / "model-card.md").write_text("\n".join(lines) + "\n", encoding="utf8", newline="\n")

    sim_lines = [
        "# Simulation",
        "",
        "`pipeline/simulate.py` steps a fictional insurer's workforce forward one month at a time for",
        f"36 months ending {end:%B %Y}. Each month: ratings (February), pay review and promotions (April),",
        "transfers, manager changes, overtime, exits, then hiring to backfill most leavers and grow the",
        "bancassurance and agency channels.",
        "",
        "Each active employee's monthly chance of resigning is a department base rate multiplied by:",
        "",
        "| Factor | Multiplier |",
        "|---|---|",
        *[f"| {k.replace('_', ' ')} | {v} |" for k, v in EFFECTS.items()],
        "",
        "Retirement happens at 58.5 years; involuntary exits depend on a rating of 1; PKWT staff can leave",
        "when a contract anniversary passes unrenewed.",
    ]
    if counts:
        sim_lines += [
            "",
            "## Rows loaded",
            "",
            "| Table | Rows |",
            "|---|---|",
            *[f"| `{k}` | {v:,} |" for k, v in counts.items()],
        ]
    (DOCS / "simulation.md").write_text("\n".join(sim_lines) + "\n", encoding="utf8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-db", action="store_true")
    parser.add_argument("--end", type=date.fromisoformat)
    args = parser.parse_args()
    started = time.perf_counter()
    end = args.end or last_full_month()
    sim = simulate(end, seed=SEED)
    trained, current = mdl.train(sim.snapshots, sim.months, seed=7)
    scores = mdl.score(trained, current)
    counts = None

    if not args.no_db:
        url = os.environ.get("DATABASE_URL") or _env_file("DATABASE_URL")
        with psycopg.connect(url, prepare_threshold=None) as conn:
            counts = build_warehouse(conn, sim)
            with conn.cursor() as cur:
                with cur.copy(
                    "COPY fact_attrition_score (scored_month, employee_id, probability, risk_band, drivers, model_version) FROM STDIN"
                ) as cp:
                    for r in scores.itertuples():
                        cp.write_row(
                            (
                                r.month,
                                r.employee_id,
                                r.probability,
                                r.risk_band,
                                json.dumps(r.drivers),
                                trained.version,
                            )
                        )
                cur.execute(
                    "INSERT INTO model_runs (version, metrics, fairness, importance, calibration, notes) VALUES (%s, %s, %s, %s, %s, %s)",
                    (
                        trained.version,
                        json.dumps(trained.metrics),
                        json.dumps(trained.fairness),
                        json.dumps(trained.importance),
                        json.dumps(trained.calibration),
                        "Synthetic data; see docs/model-card.md",
                    ),
                )
                password = (os.environ.get("DEMO_PASSWORD") or "arunika-demo").encode()
                hashed = bcrypt.hashpw(password, bcrypt.gensalt(10)).decode()
                cur.executemany(
                    "INSERT INTO users (email, password_hash, role, departments, label) VALUES (%s, %s, %s, %s, %s)",
                    [
                        (
                            "hr.admin@arunikalife.example",
                            hashed,
                            "HR_ADMIN",
                            [],
                            "HR analytics admin",
                        ),
                        (
                            "hrbp@arunikalife.example",
                            hashed,
                            "HRBP",
                            ["CLM", "POL", "CSV", "UW"],
                            "HRBP, Technical & Operations",
                        ),
                        (
                            "leader@arunikalife.example",
                            hashed,
                            "LEADER",
                            [],
                            "Director (aggregates only)",
                        ),
                    ],
                )
            conn.commit()
            counts["fact_attrition_score"] = len(scores)

    write_docs(trained, end, counts)
    m = trained.metrics
    print(
        json.dumps(
            {
                "version": trained.version,
                "roc_auc": m["roc_auc"],
                "pr_auc": m["pr_auc"],
                "ceiling": m["ceiling"],
                "base_rate": m["base_rate"],
                "point_in_time": m["point_in_time"],
                "top_features": [r["feature"] for r in trained.importance[:6]],
                "rows": counts,
                "seconds": round(time.perf_counter() - started, 1),
            },
            indent=2,
        )
    )


def _env_file(key: str) -> str:
    env = Path(__file__).resolve().parents[1] / ".env"
    for line in env.read_text(encoding="utf8").splitlines():
        if line.startswith(f"{key}="):
            return line.split("=", 1)[1].strip()
    raise SystemExit(f"{key} is not set")


if __name__ == "__main__":
    main()
